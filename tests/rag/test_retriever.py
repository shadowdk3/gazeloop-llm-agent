from unittest.mock import MagicMock, patch

from src.rag.retriever import RAGRetriever

def create_mock_retriever(sample_rows, mock_vector):
    """Create a retriever with mocked embedding and database services."""

    retriever = RAGRetriever()

    # Use a default mock vector if none is provided.
    if mock_vector is None:
        mock_vector = [0.1] * 768

    # Simulate the embedding returned for an incident description.
    retriever.embedder.embed = MagicMock(
        return_value=mock_vector
    )

    # Create a fake database connection and cursor.
    mock_conn = MagicMock()
    
    # Mock the cursor returned by conn.cursor().
    mock_cursor = mock_conn.cursor.return_value
    
    # Simulate rows returned by PostgreSQL.
    mock_cursor.fetchall.return_value = sample_rows

    return retriever, mock_conn, mock_cursor

@patch.object(RAGRetriever, "get_db_connection")
def test_retrieval_for_standing_person(mock_get_connection):
    """
    Test retrieval when the incident description says
    that a person is standing.
    """
    
    # These rows represent the results that a real database
    # might return for this query.
    #
    # The similarity scores are manually assigned here.
    # They are NOT calculated by this mock test.
    sample_rows = [
        (
            "fall_response.md",
            "1. Incident Verification",
            "Verify whether a person has fallen.",
            0.82,
        ),
        (
            "fall_response.md",
            "2. Immediate Response",
            "Check whether the person is conscious.",
            0.45,
        ),
    ]

    # Create a fake embedding vector for this test.
    # The vector is manually specified, not generated by Ollama.
    mock_vector = [0.2] * 768

    # Create the retriever with mocked embedding and database results.
    retriever, mock_conn, mock_cursor = create_mock_retriever(
        sample_rows, mock_vector
    )
    
    # When retrieve() requests a database connection,
    # return our fake database connection instead.
    mock_get_connection.return_value = mock_conn

    # Incident description used as the retrieval query.
    query = "A person is standing."

    # Execute the real retrieve() method.
    # The embedding and database operations are mocked.
    results = retriever.retrieve(query, top_k=3)

    # Display the test query and mock embedding.
    print("\n========== RETRIEVAL TEST ==========")
    print("Query:", query)
    print("Embedding vector (first 5 values):",
          retriever.embedder.embed.return_value[:5])

    for result in results:
        print("\nDocument:", result.document_name)
        print("Section:", result.section)
        print("Content:", result.content)
        print("Similarity:", result.similarity)

    # Verify that the mock database returned two rows.
    assert len(results) == 2
    
    # Verify that the first returned row has the expected score.
    assert results[0].similarity == 0.82
    
    # Verify that the second returned row has the expected score.
    assert results[1].similarity == 0.45

    # Verify that the query was passed to the embedding service.
    retriever.embedder.embed.assert_called_once_with(query)


@patch.object(RAGRetriever, "get_db_connection")
def test_retrieval_for_unresponsive_person(mock_get_connection):
    """
    Test retrieval when the incident description says
    that a person has fallen and is not responding.
    """
    
    # These are different predefined database results.
    #
    # The Immediate Response section has a higher similarity
    # score because we manually assigned it 0.91.
    sample_rows = [
        (
            "fall_response.md",
            "2. Immediate Response",
            "Check whether the person is conscious.",
            0.91,
        ),
        (
            "fall_response.md",
            "1. Incident Verification",
            "Verify whether a person has fallen.",
            0.65,
        ),
    ]

    # A different manually created mock vector for this query.
    # It does not represent a real Ollama embedding.
    mock_vector = [0.3] * 768

    # Create the retriever with this test's predefined results.
    retriever, mock_conn, mock_cursor = create_mock_retriever(
        sample_rows, mock_vector
    )
    mock_get_connection.return_value = mock_conn

    # This query describes a more serious incident.
    query = "A person has fallen and is not responding."

    # Execute retrieve() using the mock embedding and database.
    results = retriever.retrieve(query, top_k=3)

    print("\n========== RETRIEVAL TEST ==========")
    print("Query:", query)
    print("Embedding vector (first 5 values):",
          retriever.embedder.embed.return_value[:5])

    for result in results:
        print("\nDocument:", result.document_name)
        print("Section:", result.section)
        print("Content:", result.content)
        print("Similarity:", result.similarity)

    # Verify that two predefined rows were returned.
    assert len(results) == 2
   
    # The first row was manually assigned a similarity of 0.91.
    assert results[0].similarity == 0.91
    
    # The second row was manually assigned a similarity of 0.65.
    assert results[1].similarity == 0.65

    retriever.embedder.embed.assert_called_once_with(query)
