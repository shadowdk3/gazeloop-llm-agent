def build_safety_prompt(visual_description, retrieved_chunks):
    """
    Build a prompt for workplace safety analysis.

    Combine the visual observation with relevant safety guidelines
    retrieved from the knowledge database.

    Args:
        visual_description: Description generated by the vision model.
        retrieved_chunks: Relevant safety guideline chunks.

    Returns:
        A formatted prompt string for the LLM.
    """
    
    # Loop through all retrieved guideline chunks.
    # Add the document name and section as source information.
    # Combine the content into one string with blank lines between chunks.
    context = "\n\n".join(
        f"[Source: {chunk.document_name} — {chunk.section}]\n"
        f"{chunk.content}"
        for chunk in retrieved_chunks
    )

    return f"""
You are assisting with a workplace safety event.

Visual observation:
{visual_description}

Relevant safety policy:
{context}

Based only on the visual observation and the provided safety policy:

1. Summarize what is visibly observed.
2. Recommend the appropriate safety actions according to the policy.
3. List the policy sources used.

Do not invent safety procedures that are not present in the provided policy.

Return your answer in this format:

Observation:
...

Recommendation:
...

Sources:
- document — section
"""